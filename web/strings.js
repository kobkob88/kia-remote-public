let table = EN;

/** t('key', {n: 3}) -> the string with {n} filled. Unknown keys show the key (visible in testing). */
export function t(key, vars) {
  let s = table[key];
  if (s === undefined) return key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Fill every [data-t] (textContent), [data-t-aria] (aria-label) and [data-t-ph] (placeholder). */
export function applyStrings(root = document) {
  for (const el of root.querySelectorAll('[data-t]')) el.textContent = t(el.dataset.t);
  for (const el of root.querySelectorAll('[data-t-aria]')) el.setAttribute('aria-label', t(el.dataset.tAria));
  for (const el of root.querySelectorAll('[data-t-ph]')) el.setAttribute('placeholder', t(el.dataset.tPh));
}
